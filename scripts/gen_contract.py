"""Single source of truth for what the apps may send to the backend.

Reads the backend's own constants/defaults and writes
  contract/preferences.json                           (for any client: mobile, desktop, docs)
  desktop/src/shared/contract.generated.ts            (typed constants for the Electron app)

    python scripts/gen_contract.py           # regenerate
    python scripts/gen_contract.py --check   # exit 1 if the files are stale (CI / tests)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "src"))

from clipsmith import models  # noqa: E402

JSON_PATH = ROOT / "contract" / "preferences.json"
TS_PATH = ROOT / "desktop" / "src" / "shared" / "contract.generated.ts"


def build_contract() -> dict:
    return {
        "niches": list(models.NICHES),
        "paces": list(models.PACES),
        "caption_styles": list(models.CAPTION_STYLES),
        "source_types": list(models.SOURCE_TYPES),
        "languages": list(models.LANGUAGES),
        "job_statuses": list(models.JOB_STATUSES),
        "limits": {
            "target_minutes": list(models.TARGET_MINUTES_RANGE),
            "num_shorts": list(models.SHORTS_RANGE),
            "niche_notes_max_chars": models.NOTES_MAX_CHARS,
        },
        "defaults": models.Preferences().to_dict(),
    }


def render_json(contract: dict) -> str:
    return json.dumps(contract, indent=2, ensure_ascii=False) + "\n"


def render_ts(contract: dict) -> str:
    body = json.dumps(contract, indent=2, ensure_ascii=False)
    return (
        "// GENERATED by scripts/gen_contract.py from the backend models. Do not edit by hand.\n"
        f"export const CONTRACT = {body} as const;\n\n"
        "export type Niche = (typeof CONTRACT.niches)[number];\n"
        "export type Pace = (typeof CONTRACT.paces)[number];\n"
        "export type CaptionStyle = (typeof CONTRACT.caption_styles)[number];\n"
        "export type SourceType = (typeof CONTRACT.source_types)[number];\n"
        "export type JobStatus = (typeof CONTRACT.job_statuses)[number];\n"
    )


def expected_files() -> dict[Path, str]:
    c = build_contract()
    return {JSON_PATH: render_json(c), TS_PATH: render_ts(c)}


def main(argv: list[str]) -> int:
    files = expected_files()
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in files.items() if not p.exists() or p.read_text() != text]
        if stale:
            print("Stale contract files (run scripts/gen_contract.py): " + ", ".join(stale), file=sys.stderr)
            return 1
        return 0
    for path, text in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print("wrote", path.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
